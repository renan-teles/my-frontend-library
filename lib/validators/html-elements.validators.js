export function isElement(value) {
  return value instanceof Element;
}

export function isHTMLElement(value) {
  return value instanceof HTMLElement;
}

export function isHTMLInputElement(value) {
  return value instanceof HTMLInputElement;
}

export function isHTMLButtonElement(value) {
  return value instanceof HTMLButtonElement;
}

export function isHTMLSelectElement(value) {
  return value instanceof HTMLSelectElement;
}

export function isHTMLFormElement(value) {
  return value instanceof HTMLFormElement;
}

export function isNode(value) {
  return value instanceof Node;
}
